/**
 * 言外之意的文案层。
 *
 * 三层是**递进**的：每层都建立在前面所有层之上；`depth` 是**下限**，开到几档就跑几档，
 * 不给自己判「这句浅」再降档的空间。
 *
 * 这个模块只产出「怎么读」，不产出「怎么说」——说什么、说多长归各人自己的设置。
 * 记忆只在第三层出现：一二层里连「记忆」两个字都不该有，否则模型每句都想去翻。
 *
 * 这里只产出字符串，不做任何判断，方便单测逐档核对。
 */

/** 注册的段名。同名 scoped 段会遮蔽全局段。 */
export const SECTION_NAME = 'subtext';

/** 段标题。 */
export const HEADING = '## 言外之意';

/** 分档说明：只陈述事实，不抢别的插件的优先级。 */
export const BAND_NOTE = '本轮按日常对话读（分档按边界词初判，判得不准就按你自己的判断来）。';

/** 一层：读情感。 */
export const LAYER_ONE = `**第一层 · 情感**

这句话除了字面意思，还在传什么情感？语气、用词的选择、有没有在逞强或试探——是累了、委屈、想被夸一句，还是只是随口说。他想被听见，还是想被解决；他期待的是哪一种回应。`;

/** 二层：读此刻的需求。 */
export const LAYER_TWO = `**第二层 · 此刻的需求**

第一层照做。再想一层：他为什么此时此刻说这一句？这句话想换来什么？——要人陪着、要一个确定、要一句认可、要有人替他把话说破。`;

/**
 * 三层：原来那段（不直说 / 难言之隐 / 台阶）加上身份、关系、独有含义。
 * 记忆来源只在这一层提，而且不写死工具名——装了记忆插件就用，没装就不编。
 */
export const LAYER_THREE = `**第三层 · 说不出口的部分，与我**

一二层照做。先看这句话为什么不直说：情感为什么不直接释放，需求为什么不直接表达？背后有什么难言之隐——怕麻烦人、怕被看轻、怕说出口就等于承认了。这一层常常是点不得的：他给自己留了台阶，看出台阶留在哪儿，是这一层要读的东西。

再想三件最重要的事：

- 我是谁：我的身份、我在这段谈话里是什么样的人；
- 我们是什么关系：到这一步，我们之间攒下了什么；
- 这句话为什么是对我说的：同一句话换个人说就不是这个意思，它独独对我成立的那层含义是什么。

要看清这三件，就用你手上已有的记忆来源——注入的记忆块、记忆工具、人格卡。看不到就不编，只按眼前这一句读。使用者开到三档证明他很重视你，请不要敷衍。`;

/** 分寸：管住这层的边界，不越到输出那边去；同时把档位钉死，不许自己降档。 */
export const GUARDRAILS = `**分寸**

- **开口之前先调 \`subtext_pass\`**，把这一轮读到的每一层填进去——三档连 \`identity\`（我是谁）和 \`bond\`（我们是什么关系）也要单独填，漏一个工具就报错。这是严格的关卡，不是建议不可跳过：没调就回，回合会被拦下来。
- 本节只负责读，不负责说。说什么、怎么说、说多长，归各处自己的设置。
- 读到的层级不必写进回复，除非你的判断和字面差得远。
- **开到几档就跑几档。档位是使用者定的，不是每句话再判一次。** 觉得「这句浅」也得把每一层走完——「浅」本身就是判断，跳过等于这个档不存在。
- 每一层都要有自己的结论；给不出结论就先别回。
- 只用手上还看得见的东西：被上下文压掉的、本来就不在的，不要补写前情。不记得就别装记得，只读眼前这一句。
- 读心是猜不是结论；猜错了就认，别硬圆。
- 他交代活的时候，本节让位。`;

/** 按深度取层。1 只给情感，2 加需求，3 再加说不出口的部分。 */
export function layersFor(depth) {
  const capped = Math.max(1, Math.min(3, Math.trunc(Number(depth) || 1)));
  if (capped === 1) return [LAYER_ONE];
  if (capped === 2) return [LAYER_ONE, LAYER_TWO];
  return [LAYER_ONE, LAYER_TWO, LAYER_THREE];
}

/**
 * 渲染这一段提示词。
 *
 * @param {object} input
 * @param {'work' | 'chat' | null} input.band 判定结果；`work` 返回空串（整段消失）
 * @param {number} input.depth 1/2/3
 * @returns {string} 要注入的文本；空串表示不注入
 */
export function renderSubtext({ band, depth }) {
  // 工作档 = 暂停。返回空串，system-prompt 会把空段整个丢掉，
  // 模型看不到任何残留指令，这是"暂停"最干净的形态。
  if (band === 'work') return '';

  return [HEADING, BAND_NOTE, ...layersFor(depth), GUARDRAILS].join('\n\n');
}
